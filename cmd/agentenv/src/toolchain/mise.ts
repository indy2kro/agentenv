/**
 * Tools agentenv invokes directly are pinned to versions we have verified;
 * everything else resolves to latest. rtk is invoked by agentenv's delegation
 * (its `init` flags are the hook contract), moves fast, and must stay pinned —
 * bump deliberately per plan §10.
 */
export const PINNED_TOOL_VERSIONS: Record<string, string> = {
  rtk: '0.49.0',
};

/**
 * Generate mise.toml content from agentenv config
 */
export function generateMiseToml(
  config: AgentenvConfig,
  customTools: Array<{
    name: string;
    mise_source?: string;
    version?: string;
  }> = [],
): string {
  const lines: string[] = [];

  lines.push('# mise.toml - Generated by agentenv');
  lines.push('# Do not edit directly; edit agentenv.toml instead');
  lines.push('');

  // Tools section
  lines.push('[tools]');

  const tools = config.tools || {};
  const toolKeys = Object.keys(tools) as Array<keyof typeof tools>;

  // Process tools by tier
  const tier1Tools = toolKeys.filter((key) => TOOL_TIERS[key] === 1 && tools[key]);
  const tier2Tools = toolKeys.filter((key) => TOOL_TIERS[key] === 2 && tools[key]);
  const tier3Tools = toolKeys.filter((key) => TOOL_TIERS[key] === 3 && tools[key]);

  // Add enabled tools
  const allEnabledTools = [...tier1Tools, ...tier2Tools, ...tier3Tools];

  for (const toolKey of allEnabledTools) {
    // Skip tools that require fallback installation (not in mise registry)
    if (requiresFallback(toolKey) || isPlatformUnsupported(toolKey)) {
      continue;
    }
    const miseName = MISE_TOOL_NAMES[toolKey] || toolKey;
    const version = PINNED_TOOL_VERSIONS[miseName] || config.tool_versions?.[toolKey] || 'latest';
    lines.push(`${miseName} = "${version}"`);
  }

  // Add custom tools with mise_source
  for (const ct of customTools) {
    if (ct.mise_source) {
      const version = ct.version || 'latest';
      lines.push(`\n# Custom tool: ${ct.name}`);
      lines.push(`${ct.mise_source} = "${version}"`);
    }
  }

  lines.push('');

  // Env section for agentenv-specific variables
  lines.push('[env]');
  lines.push('AGENTENV_MANAGED = "true"');
  lines.push('');

  return lines.join('\n');
}

/**
 * Directory where agentenv asks mise to place shims (~/.local/bin). Shim files
 * are what make the installed tools resolve by name ("difft", "rg", ...) from
 * any shell — PowerShell, cmd, bash or the agents themselves.
 */
export function shimsDir(): string {
  return path.join(os.homedir(), '.local', 'bin');
}

/**
 * mise's global config directory. `shims_dir` is deliberately NOT honored in a
 * project/`MISE_CONFIG_FILE` config — mise ignores it there with a warning
 * ("ignored for security reasons") — so it must live in the global config.
 */
export function miseGlobalConfigDir(): string {
  return path.join(os.homedir(), '.config', 'mise');
}

export function miseGlobalConfigPath(): string {
  return path.join(miseGlobalConfigDir(), 'config.toml');
}

/**
 * True when a PATH variable entry resolves to the given directory
 * (case-folded on Windows where PATH entries and real paths often differ in
 * case).
 */
export function pathContainsDir(pathVar: string, dir: string): boolean {
  const target = path.resolve(dir);
  const want = process.platform === 'win32' ? target.toLowerCase() : target;
  return pathVar
    .split(path.delimiter)
    .filter((entry) => entry.trim() !== '')
    .some((entry) => {
      const resolved = path.resolve(entry);
      const have = process.platform === 'win32' ? resolved.toLowerCase() : resolved;
      return have === want;
    });
}

/** Whether the shims dir (~/.local/bin) is already resolvable from PATH. */
export function shimsDirOnPath(): boolean {
  return pathContainsDir(process.env.PATH ?? '', shimsDir());
}

/**
 * Line-based insert/update of `shims_dir = "<dir>"` under `[settings]` in a
 * mise config. Surgical on purpose: the global mise config may carry the
 * user's own comments/settings, and a full TOML round-trip would destroy them.
 */
export function upsertShimsDir(content: string, dir: string): string {
  const shimsLine = `shims_dir = "${tomlPath(dir)}"`;
  const lines = content.split('\n');
  const headerIdx = lines.findIndex((line) => /^\s*\[settings\]\s*$/.test(line));
  if (headerIdx === -1) {
    const trimmed = content.trimEnd();
    return trimmed === ''
      ? `[settings]\n${shimsLine}\n`
      : `${trimmed}\n\n[settings]\n${shimsLine}\n`;
  }
  const nextHeader = lines.findIndex((line, i) => i > headerIdx && /^\s*\[[^[]/.test(line));
  const end = nextHeader === -1 ? lines.length : nextHeader;
  const existing = lines.slice(headerIdx, end).findIndex((line) => /^\s*shims_dir\s*=/.test(line));
  if (existing !== -1) {
    lines[headerIdx + existing] = shimsLine;
    return lines.join('\n');
  }
  lines.splice(headerIdx + 1, 0, shimsLine);
  return lines.join('\n');
}

/**
 * Extract the `shims_dir` value mise would honor from `[settings]` in a mise
 * config, or null when it is absent. Used by `agentenv doctor`.
 */
export function getShimsDirValue(content: string): string | null {
  const lines = content.split('\n');
  const headerIdx = lines.findIndex((line) => /^\s*\[settings\]\s*$/.test(line));
  if (headerIdx === -1) return null;
  for (let i = headerIdx + 1; i < lines.length; i++) {
    if (/^\s*\[[^[]/.test(lines[i])) break;
    const match = lines[i].match(/^\s*shims_dir\s*=\s*"([^"]+)"/);
    if (match) return match[1];
  }
  return null;
}

/**
 * Ensure mise's GLOBAL config declares the shims_dir agentenv relies on, and
 * tell the user whether the shims dir is actually on PATH. Idempotent.
 */
export function ensureGlobalShimsDir(): {
  success: boolean;
  message: string;
} {
  const dir = shimsDir();
  const configPath = miseGlobalConfigPath();
  try {
    fs.mkdirSync(miseGlobalConfigDir(), { recursive: true });
    const existing = fs.existsSync(configPath) ? fs.readFileSync(configPath, 'utf-8') : '';
    const updated = upsertShimsDir(existing, dir);
    if (updated !== existing) fs.writeFileSync(configPath, updated);

    const pathLine = shimsDirOnPath()
      ? `${dir} is on PATH`
      : `Add ${dir} to PATH so the shims resolve (Windows: System Properties > Environment Variables > Path)`;
    if (updated !== existing) {
      return {
        success: true,
        message: `mise: set shims_dir in ${configPath}; ${pathLine}`,
      };
    }
    return {
      success: true,
      message: `mise: shims_dir already set (${tomlPath(dir)}); ${pathLine}`,
    };
  } catch (err) {
    return {
      success: false,
      message: `Failed to configure mise shims_dir: ${err instanceof Error ? err.message : String(err)}`,
    };
  }
}

/** Format a path for embedding in a TOML string (mise wants forward slashes). */
function tomlPath(p: string): string {
  return p.replace(/\\/g, '/');
}

/**
 * Save mise.toml to a file
 */
export function saveMiseToml(content: string, outputPath: string): void {
  try {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    const result = writeFileWithVerify(outputPath, content);
    if (!result.success) throw new Error(result.message);
  } catch (err) {
    throw new Error(
      `Failed to save mise.toml: ${err instanceof Error ? err.message : String(err)}`,
      { cause: err },
    );
  }
}

/**
 * Get list of tools to install from config
 */
export function getToolsToInstall(config: AgentenvConfig): Array<{
  name: string;
  miseName: string;
  version: string;
  tier: number;
}> {
  const tools = config.tools || {};
  const toolKeys = Object.keys(tools) as Array<keyof typeof tools>;

  const result: Array<{
    name: string;
    miseName: string;
    version: string;
    tier: number;
  }> = [];

  for (const key of toolKeys) {
    if (tools[key]) {
      // Skip tools that require fallback installation (not in mise registry)
      if (requiresFallback(key) || isPlatformUnsupported(key)) {
        continue;
      }
      const miseName = MISE_TOOL_NAMES[key] || key;
      result.push({
        name: key,
        miseName,
        version: PINNED_TOOL_VERSIONS[miseName] || config.tool_versions?.[key] || 'latest',
        tier: TOOL_TIERS[key] || 3,
      });
    }
  }

  return result;
}

/**
 * The mise tool names `agentenv update` may safely bump: enabled, non-fallback
 * tools that resolve to `latest`. Pinned tools (rtk's code pin and any
 * `agentenv.toml [tool_versions]` entry) are excluded so `mise up` never moves
 * a version the user (or the hook contract) chose to pin.
 */
export function getUpgradeableTools(config: AgentenvConfig): string[] {
  return getToolsToInstall(config)
    .filter((tool) => tool.version === 'latest')
    .map((tool) => tool.miseName);
}

/**
 * Update mise itself. Unattended (`MISE_YES=1`); surfaces stderr as-is because
 * some install methods (e.g. winget) do not support in-place self-updates and
 * the user must see that instead of a silent no-op.
 */
export async function runMiseSelfUpdate(): Promise<{
  success: boolean;
  output: string;
}> {
  try {
    const result = child_process.spawnSync('mise', ['self-update'], {
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'pipe'],
      env: { ...process.env, MISE_YES: '1' },
    });
    const output = (result.stdout || result.stderr || '').trim();
    return { success: result.status === 0, output };
  } catch (err) {
    return {
      success: false,
      output: err instanceof Error ? err.message : String(err),
    };
  }
}

/**
 * Bump the given `mise up` targets to their latest versions within the current
 * config constraints (pins stay put because pinned tools are not passed in).
 */
export async function runMiseUpgrade(
  tools: string[],
  cwd: string,
): Promise<{
  success: boolean;
  stdout: string;
  stderr: string;
  exitCode: number | null;
}> {
  try {
    const result = child_process.spawnSync('mise', ['up', ...tools], {
      cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return {
      success: result.status === 0,
      stdout: result.stdout || '',
      stderr: result.stderr || '',
      exitCode: result.status ?? null,
    };
  } catch (err) {
    return {
      success: false,
      stdout: '',
      stderr: err instanceof Error ? err.message : String(err),
      exitCode: null,
    };
  }
}

/**
 * Uninstall the given tools from the mise store. Each tool name is passed
 * version-less (no `@version`) together with `--all`, removing every installed
 * version of that tool. `--all` is required: without it, mise 2026.x bails with
 * "multiple tools specified, use --all to uninstall all versions" as soon as a
 * named tool has more than one version installed. Surfaces the captured
 * subprocess result like runMiseUpgrade does.
 */
export function runMiseUninstall(
  tools: string[],
  cwd: string = '.',
  miseTomlPath?: string,
): {
  success: boolean;
  stdout: string;
  stderr: string;
  exitCode: number | null;
} {
  const result = runMiseCaptured(['uninstall', '--all', ...tools], { cwd, miseTomlPath });
  return {
    success: result.status === 0,
    stdout: result.stdout || '',
    stderr: result.stderr || '',
    exitCode: result.status ?? null,
  };
}

export interface RunMiseCapturedOptions {
  cwd?: string;
  /** When known, point mise at the project's mise.toml via MISE_CONFIG_FILE. */
  miseTomlPath?: string;
}

export interface MiseCapturedOutput {
  status: number | null;
  stdout: string;
  stderr: string;
  blockedWarn: boolean;
}

/**
 * Run a single mise command with args passed as an array (never a
 * string-built command — paths with spaces would break parsing on Windows)
 * and with stderr captured instead of inherited. This is the one funnel every
 * mise capture goes through so a `mise WARN` update notice on stderr can
 * never leak into agentenv's stdout.
 */
export function runMiseCaptured(
  args: string[],
  opts: RunMiseCapturedOptions = {},
): MiseCapturedOutput {
  const env = opts.miseTomlPath
    ? { ...process.env, MISE_CONFIG_FILE: opts.miseTomlPath }
    : process.env;
  let result: child_process.SpawnSyncReturns<string>;
  try {
    result = child_process.spawnSync('mise', args, {
      cwd: opts.cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'pipe'],
      env,
    });
  } catch (err) {
    return {
      status: null,
      stdout: '',
      stderr: err instanceof Error ? err.message : String(err),
      blockedWarn: false,
    };
  }
  const stderr = result.error ? result.error.message : (result.stderr ?? '');
  return {
    status: result.status,
    stdout: result.stdout ?? '',
    stderr,
    blockedWarn: /warn|self-update|version .* available/i.test(stderr),
  };
}

/**
 * Check if a specific tool is installed via mise
 */
export function isMiseInstalled(): boolean {
  return runMiseCaptured(['--version']).status === 0;
}

/**
 * Get mise version. The probe is silent by construction: it only reads
 * stdout, never surfaces whatever mise may have written to stderr (a
 * `mise WARN release available` update notice is not truth about the
 * installed version, so it is dropped here).
 */
export function getMiseVersion(): string {
  const result = runMiseCaptured(['--version']);
  const version = result.stdout.trim();
  return result.status === 0 && version !== '' ? version : 'unknown';
}

/** Alias used by prereq/status/doctor so version probes never surface mise WARN. */
export function getMiseVersionSilent(): string {
  return getMiseVersion();
}

/**
 * Check if a specific tool is installed via mise
 */
export function isToolInstalled(toolName: string): boolean {
  return runMiseCaptured(['which', toolName]).status === 0;
}

/**
 * Install mise itself
 * This should be done by the user before running agentenv
 */
export function ensureMiseInstalled(): {
  success: boolean;
  message: string;
} {
  if (isMiseInstalled()) {
    return {
      success: true,
      message: `mise is already installed (${getMiseVersion()})`,
    };
  }

  return {
    success: false,
    message:
      "mise is not installed. agentenv uses mise to install and manage this project's tools.\n" +
      miseInstallInstructions().join('\n'),
  };
}

