/**
 * Platform-specific instructions for installing mise, used for self-diagnosis
 * when `mise` is missing from PATH.
 */
export function miseInstallInstructions(): string[] {
  const lines = ['To install mise, run one of the following:'];

  if (process.platform === 'win32') {
    lines.push('  winget install jdx.mise');
    lines.push('  # or: irm https://mise.jdx.dev/install.ps1 | iex');
  } else if (process.platform === 'darwin') {
    lines.push('  brew install mise');
  } else {
    lines.push('  curl https://mise.jdx.dev/install.sh | sh');
  }

  lines.push('Then open a new terminal so `mise` is available on PATH.');
  lines.push('Full docs: https://mise.jdx.dev/getting-started.html');
  return lines;
}

/**
 * Mark the generated mise.toml as trusted so `mise` (and the shims it creates)
 * actually use it in this directory. Idempotent: re-trusting is a no-op success.
 */
export function trustMiseToml(
  miseTomlPath: string,
  cwd: string = '.',
): {
  success: boolean;
  message: string;
} {
  const result = runMiseCaptured(['trust', miseTomlPath], { cwd });
  if (result.status === 0) {
    return { success: true, message: `Trusted ${miseTomlPath} (mise trust)` };
  }
  const detail = (result.stderr || result.stdout || '').trim();
  if (result.status === null && detail) {
    return { success: false, message: `mise trust errored: ${detail}` };
  }
  return {
    success: false,
    message: `mise trust failed (exit ${result.status ?? 'null'}): ${detail}`,
  };
}

/**
 * Turn raw `mise install` output into a truthful one-liner, so "already
 * installed" runs don't imply anything new was fetched.
 */
export function miseInstallOutcome(stdout: string): string {
  const match = stdout.match(/installed (\d+) tools?/);
  if (match) {
    const installed = Number(match[1]);
    if (installed === 0)
      return 'mise install completed (tools already installed, nothing to fetch)';
    return `mise install completed (installed ${installed} tool${installed === 1 ? '' : 's'})`;
  }
  return 'mise install completed';
}

export type ToolResolvability = 'resolvable' | 'needs-new-terminal' | 'missing';

export interface ToolAvailability {
  key: string;
  binary: string;
  onPath: boolean;
  status: ToolResolvability;
}

/**
 * True when a shim file for `binary` exists on disk under `dir` (case-folded,
 * and accepting the .exe/.cmd/.bat suffix Windows shims get). This is what
 * distinguishes "installed, just not on this stale PATH's resolve set" from
 * "not installed at all" — a new terminal picks the shim up from here.
 */
export function shimExistsIn(binary: string, dir: string): boolean {
  let entries: string[];
  try {
    entries = fs.readdirSync(dir);
  } catch {
    return false;
  }
  const base = binary.toLowerCase();
  return entries.some((entry) => {
    const name = entry.toLowerCase();
    return (
      name === base || name === `${base}.exe` || name === `${base}.cmd` || name === `${base}.bat`
    );
  });
}

/** Whether the shim for `binary` exists in the common shims dir (~/.local/bin). */
export function shimExists(binary: string): boolean {
  return shimExistsIn(binary, shimsDir());
}

/**
 * The three-state verdict for one binary. `resolvable` means it is on the
 * current PATH; `needs-new-terminal` means it is installed (a mise shim exists
 * on disk under the shims dir) but the current shell's PATH is stale; `missing`
 * means neither — the only case that is a genuine failure.
 */
export function classifyToolResolvability(
  onPath: boolean,
  shimPresent: boolean,
  isWindows: boolean = process.platform === 'win32',
): ToolResolvability {
  if (onPath) return 'resolvable';
  if (isWindows && shimPresent) return 'needs-new-terminal';
  return 'missing';
}

export function toolResolvability(binary: string): ToolResolvability {
  return classifyToolResolvability(resolveBinary(binary) !== null, shimExists(binary));
}

/**
 * After `mise install`, check which enabled tools actually resolve on PATH so
 * setup/apply can report honestly whether shims are active in this shell. On
 * Windows an installed tool that is only reachable from a *new* terminal is
 * classified `needs-new-terminal`, not `missing`.
 */
export function verifyToolAvailability(config: AgentenvConfig): ToolAvailability[] {
  const tools = config.tools || {};
  const result: ToolAvailability[] = [];
  for (const key of TOOL_KEYS) {
    if (tools[key] !== true) continue;
    const binary = BINARY_MAP[key];
    const onPath = resolveBinary(binary) !== null;
    result.push({
      key,
      binary,
      onPath,
      status: classifyToolResolvability(onPath, shimExists(binary)),
    });
  }
  return result;
}

export interface VerifyCounts {
  resolvable: number;
  needsNewTerminal: number;
  missing: number;
}

export function verifyCounts(availability: ToolAvailability[]): VerifyCounts {
  const counts: VerifyCounts = { resolvable: 0, needsNewTerminal: 0, missing: 0 };
  for (const tool of availability) {
    if (tool.status === 'resolvable') counts.resolvable++;
    else if (tool.status === 'needs-new-terminal') counts.needsNewTerminal++;
    else counts.missing++;
  }
  return counts;
}

/**
 * Shared summary line used by `apply` and `update`. The old
 * "N/M configured tools resolve on PATH" phrasing is kept only as a superset
 * when something is not immediately resolvable.
 */
export function verifySummaryLine(availability: ToolAvailability[]): string {
  const counts = verifyCounts(availability);
  const base = `Verify: ${counts.resolvable} resolvable / ${counts.needsNewTerminal} need a new terminal / ${counts.missing} missing`;
  if (counts.needsNewTerminal + counts.missing > 0) {
    return `${base} — ${counts.resolvable}/${availability.length} configured tools resolve on PATH now`;
  }
  return base;
}

/** One line per tool, symbol-prefixed (commands add their own indentation). */
export function toolAvailabilityLine(tool: ToolAvailability): string {
  if (tool.status === 'resolvable') return `✓ ${tool.binary} (${tool.key})`;
  if (tool.status === 'needs-new-terminal') {
    return `~ ${tool.binary} (${tool.key}) — installed; open a new terminal`;
  }
  return `✗ ${tool.binary} (${tool.key}) — not installed (mise install did not produce it)`;
}

/**
 * Whether the activation hint should be shown at all: only when at least one
 * tool is installed-but-stale or missing. Emitted once per run by the caller.
 */
export function verifyHintNeeded(availability: ToolAvailability[]): boolean {
  return availability.some(
    (tool) => tool.status === 'needs-new-terminal' || tool.status === 'missing',
  );
}

/**
 * Concise, actionable guidance for the case where tools are installed via mise
 * but are not yet resolvable from the current shell.
 */
export function miseActivationHint(): string {
  if (process.platform === 'win32') {
    return [
      'Tools ARE installed via mise and resolve inside this project (shims in ~/.local/bin).',
      "If one still isn't found: open a NEW terminal in this project, or run `mise trust` + `mise install`, or `mise use -g <tool>`.",
    ].join('\n');
  }
  return [
    'Enable mise in your shell so tools resolve on PATH: add `eval "$(mise activate bash)"` to ~/.bashrc (or `mise activate zsh` for zsh).',
    'Then start a new terminal.',
  ].join('\n');
}

/**
 * Patterns that indicate an interactive acceptance prompt (EULA/license) in
 * install output. Detected so the user is told *which* tool wants acceptance
 * with a one-line instruction instead of a deadlocked/hung non-interactive run.
 */
export const EULA_PROMPT_PATTERNS: RegExp[] = [
  /\beula\b/i,
  /accept.*(?:license|terms|eula)/i,
  /\by\/n\b/i,
  /\bpress\s+(?:enter|y)\b/i,
];

/**
 * Known tools whose first install asks for a EULA. Keyed by tool name the same
 * way `verifyToolAvailability` keys tools (data-driven; never blanket-pipe
 * `yes` into a blind install).
 */
export const EULA_TOOL_NAMES: string[] = ['gitleaks'];

/** Printed before `mise install` when a known EULA-gated tool is enabled. Never auto-accepts. */
export function eulaPreflightHint(config: AgentenvConfig): string {
  const tools = config.tools || {};
  const flagged = EULA_TOOL_NAMES.filter((name) => tools[name as keyof typeof tools] === true);
  if (flagged.length === 0) return '';
  const tool = flagged[0];
  return `${tool} requires accepting a EULA on first install — run \`mise install ${tool}\` in an interactive terminal and accept it, then re-run \`agentenv apply\`.`;
}

/**
 * Printed instead of silently dropping enabled tools that mise cannot
 * install at all on this platform (see PLATFORM_UNSUPPORTED_TOOLS) — without
 * this, `generateMiseToml`/`getToolsToInstall` quietly excluding them would
 * leave the user thinking those tools installed when they never even ran.
 */
export function platformUnsupportedHint(config: AgentenvConfig): string {
  const tools = config.tools || {};
  const skipped = TOOL_KEYS.filter((key) => tools[key] === true && isPlatformUnsupported(key));
  if (skipped.length === 0) return '';
  return `Skipped on ${process.platform} (no mise backend supports it here): ${skipped.join(', ')}`;
}

export interface EulaDetection {
  eulaTools: string[];
  eulaHint: string;
}

/** Detect a likely interactive-acceptance prompt in captured install output. */
export function detectEulaPrompt(stdout: string, stderr: string): EulaDetection {
  const combined = `${stdout}\n${stderr}`;
  const prompted = EULA_PROMPT_PATTERNS.some((pattern) => pattern.test(combined));
  if (!prompted) return { eulaTools: [], eulaHint: '' };
  const tool = EULA_TOOL_NAMES.find((name) => combined.toLowerCase().includes(name));
  if (tool) {
    return {
      eulaTools: [tool],
      eulaHint: `gitleaks requires accepting a EULA on first install — run \`mise install ${tool}\` in an interactive terminal and accept it, then re-run \`agentenv apply\`.`,
    };
  }
  return {
    eulaTools: [],
    eulaHint:
      'mise install wants an interactive acceptance — run `mise install` in an interactive terminal and accept it, then re-run `agentenv apply`.',
  };
}

export interface MiseInstallResult {
  success: boolean;
  stdout: string;
  stderr: string;
  exitCode: number | null;
  /** Tools (from EULA_TOOL_NAMES) whose EULA likely needs accepting. */
  eulaTools: string[];
  /** One-line instruction for the acceptance case; empty when no prompt. */
  eulaHint: string;
}

/**
 * Run mise install
 * Installs all tools listed in mise.toml
 *
 * Runs via async `spawn` (not `spawnSync`): `mise install` can take tens of
 * seconds (downloading/extracting many tools), and a sync call would block
 * the whole Node event loop for that entire duration — freezing any ora
 * spinner (which redraws via a timer) and delaying every captured line of
 * output until the process exits. `onOutput`, when given, is called with
 * each chunk as it arrives so a caller can stream mise's own progress output
 * live instead of only seeing it after install finishes.
 */
export async function runMiseInstall(
  miseTomlPath: string,
  cwd: string = '.',
  onOutput?: (chunk: string, stream: 'stdout' | 'stderr') => void,
): Promise<MiseInstallResult> {
  const env = { ...process.env, MISE_CONFIG_FILE: miseTomlPath };
  return new Promise<MiseInstallResult>((resolve) => {
    let child: child_process.ChildProcess;
    try {
      child = child_process.spawn('mise', ['install'], {
        cwd,
        env,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
    } catch (err) {
      resolve({
        success: false,
        stdout: '',
        stderr: err instanceof Error ? err.message : String(err),
        exitCode: null,
        eulaTools: [],
        eulaHint: '',
      });
      return;
    }

    let stdout = '';
    let stderr = '';
    child.stdout?.setEncoding('utf-8').on('data', (chunk: string) => {
      stdout += chunk;
      onOutput?.(chunk, 'stdout');
    });
    child.stderr?.setEncoding('utf-8').on('data', (chunk: string) => {
      stderr += chunk;
      onOutput?.(chunk, 'stderr');
    });
    child.on('error', (err) => {
      resolve({
        success: false,
        stdout,
        stderr: stderr || err.message,
        exitCode: null,
        eulaTools: [],
        eulaHint: '',
      });
    });
    child.on('close', (code) => {
      const eula = detectEulaPrompt(stdout, stderr);
      resolve({
        success: code === 0,
        stdout,
        stderr,
        exitCode: code,
        eulaTools: eula.eulaTools,
        eulaHint: eula.eulaHint,
      });
    });
  });
}

export interface InstalledToolState {
  installed: boolean;
  versions: string[];
}

/**
 * Parse `mise ls --json` output into installed-tool state, or `null` when the
 * output is not valid JSON in a recognizable shape. mise's real output is an
 * object keyed by tool name mapping to entries like `{version, install_path,
 * installed, active}`; declared-but-uninstalled tools still appear with
 * `installed: false`. A legacy `[{name, version}]` array shape is tolerated
 * so an older/downgraded mise cannot silently regress the caller to "nothing
 * installed". Callers that mutate the store must fail closed on `null` —
 * unrecognized output is never evidence that nothing is installed.
 */
export function parseInstalledToolState(raw: string): Record<string, InstalledToolState> | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }

  const state: Record<string, InstalledToolState> = {};
  if (Array.isArray(parsed)) {
    for (const item of parsed as Array<{ name?: string; version?: string }>) {
      if (typeof item?.name !== 'string') continue;
      const entry = (state[item.name] ??= { installed: true, versions: [] });
      if (typeof item.version === 'string') entry.versions.push(item.version);
    }
    return state;
  }

  if (parsed && typeof parsed === 'object') {
    for (const [name, entries] of Object.entries(parsed as Record<string, unknown>)) {
      const list = Array.isArray(entries)
        ? (entries as Array<{ version?: string; installed?: boolean }>)
        : [];
      state[name] = {
        installed: list.some((entry) => entry.installed === true),
        versions: list
          .map((entry) => (typeof entry.version === 'string' ? entry.version : ''))
          .filter((version) => version !== ''),
      };
    }
    return state;
  }

  return null;
}

/**
 * Tolerant installed-tool state view for read-only callers: unlike
 * `parseInstalledToolState`, unparseable or unrecognized `mise ls --json`
 * output (or an absent mise) yields an empty map rather than `null`.
 */
export function getInstalledToolState(raw?: string): Record<string, InstalledToolState> {
  return parseInstalledToolState(raw ?? runMiseCaptured(['ls', '--json']).stdout) ?? {};
}

/**
 * Parse existing mise.toml file
 */
export function parseMiseToml(filePath: string): MiseConfig | null {
  try {
    if (!fs.existsSync(filePath)) {
      return null;
    }

    const content = fs.readFileSync(filePath, 'utf-8');
    return parseToml(content) as MiseConfig;
  } catch {
    return null;
  }
}

/**
 * Simple TOML parser helper
 */
function parseToml(content: string): Record<string, any> {
  const result: Record<string, any> = {};
  let currentTable: Record<string, any> = result;

  const lines = content.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();

    // Skip comments and empty lines
    if (trimmed === '' || trimmed.startsWith('#')) {
      continue;
    }

    // Section header
    if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
      const section = trimmed.slice(1, -1);

      if (section.includes('.')) {
        // Nested section
        const parts = section.split('.');
        let parent: Record<string, any> = result;

        for (let i = 0; i < parts.length - 1; i++) {
          if (!parent[parts[i]]) {
            parent[parts[i]] = {};
          }
          parent = parent[parts[i]];
        }

        currentTable = parent;
      } else {
        if (!result[section]) {
          result[section] = {};
        }
        currentTable = result[section];
      }
      continue;
    }

    // Key-value pair
    const equalsIndex = trimmed.indexOf('=');
    if (equalsIndex > 0) {
      const key = trimmed.slice(0, equalsIndex).trim();
      const value = trimmed.slice(equalsIndex + 1).trim();

      // Remove quotes if present
      let cleanValue: any = value;
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        cleanValue = value.slice(1, -1);
      }

      // Parse boolean
      if (cleanValue.toLowerCase() === 'true') {
        cleanValue = true;
      } else if (cleanValue.toLowerCase() === 'false') {
        cleanValue = false;
      }

      // Parse number
      if (!isNaN(Number(cleanValue))) {
        cleanValue = Number(cleanValue);
      }

      currentTable[key] = cleanValue;
    }
  }

  return result;
}

/**
 * Merge existing mise.toml with new tools
 * Preserves existing tools that are not in the new config
 */
export function mergeMiseConfigs(existing: MiseConfig | null, newConfig: MiseConfig): MiseConfig {
  const result: MiseConfig = {
    tools: { ...newConfig.tools },
    env: { ...newConfig.env },
    settings: { ...newConfig.settings },
  };

  if (existing) {
    // Merge tools - preserve existing versions if not in new config
    for (const [tool, version] of Object.entries(existing.tools || {})) {
      if (!result.tools[tool]) {
        result.tools[tool] = version;
      }
    }

    // Merge env
    if (existing.env) {
      for (const [key, value] of Object.entries(existing.env)) {
        if (!result.env || !result.env[key]) {
          if (!result.env) {
            result.env = {};
          }
          result.env[key] = value;
        }
      }
    }

    // Merge settings
    if (existing.settings) {
      for (const [key, value] of Object.entries(existing.settings)) {
        if (!result.settings || result.settings[key] === undefined) {
          if (!result.settings) {
            result.settings = {};
          }
          result.settings[key] = value;
        }
      }
    }
  }

  return result;
}
